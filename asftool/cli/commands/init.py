"""``asftool init`` — create a working configuration.

The preflight in ``cli/main.py`` tells a user with no configuration to
run ``asftool init`` or copy ``.env.example`` to ``.env``. This command
is the one-command version of that: it writes a ``.env`` with a freshly
generated encryption key and creates the config directory.
"""

import os
from pathlib import Path

import typer

from asftool.cli.ui import print_error, print_info, print_success, print_warning
from asftool.core.config import generate_encryption_key, generate_jwt_secret

#: The settings written by `asftool init`.
_ENV_TEMPLATE = """# ASFTool configuration
# Generated by `asftool init` on {created}.

# Application Settings
APP_NAME=asftool
APP_VERSION=0.1.0
DEBUG=false
LOG_LEVEL=INFO

# Force UTF-8 encoding for CLI output.
PYTHONIOENCODING=utf-8

# Salesforce API version. Format: v<major>.<minor>
SF_API_VERSION=v68.0
SF_DEFAULT_DOMAIN=login.salesforce.com

# Encrypts the tokens stored in the OS keyring. Keep this secret: anyone
# with it can decrypt the contents of the keyring entry.
ENCRYPTION_KEY={encryption_key}

# Internal token signing secret (not for Salesforce auth).
JWT_SECRET_KEY={jwt_secret}
"""


def _write_env(target: Path, encryption_key: str, jwt_secret: str) -> None:
    from datetime import UTC, datetime

    content = _ENV_TEMPLATE.format(
        created=datetime.now(UTC).isoformat(timespec="seconds"),
        encryption_key=encryption_key,
        jwt_secret=jwt_secret,
    )
    target.write_text(content, encoding="utf-8")
    # The file holds a secret: keep it to the owner.
    os.chmod(target, 0o600)


def init(
    path: Path = typer.Option(
        Path(".env"), "--path", "-p", help="Where to write the .env file"
    ),
    force: bool = typer.Option(
        False, "--force", "-f", help="Overwrite an existing .env"
    ),
) -> None:
    """Create a .env with a generated encryption key, and the config directory."""
    if path.exists() and not force:
        print_error(f"{path} already exists. Use --force to overwrite it.")
        raise typer.Exit(1)

    encryption_key = generate_encryption_key()
    jwt_secret = generate_jwt_secret()

    try:
        _write_env(path, encryption_key, jwt_secret)
    except OSError as e:
        print_error(f"Could not write {path}: {e}")
        raise typer.Exit(1) from e

    print_success(f"Wrote {path}")

    config_dir = Path.home() / ".asftool"
    try:
        config_dir.mkdir(parents=True, exist_ok=True)
        os.chmod(config_dir, 0o700)
        print_info(f"Config directory: {config_dir}")
    except OSError as e:
        print_warning(f"Could not create {config_dir}: {e}")

    print_info("")
    print_info("Next: asftool auth login   (opens a browser)")
    print_info("      asftool doctor       (checks the environment)")
